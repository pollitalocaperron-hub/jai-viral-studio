import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const store = readFileSync(new URL("../jai-visual-asset-store.js", import.meta.url), "utf8");
const renderer = readFileSync(new URL("../jai-media-renderer.js", import.meta.url), "utf8");
const api = readFileSync(new URL("../api/search-visual-assets.js", import.meta.url), "utf8");
assert.match(api, /original_url: original/);
assert.match(store, /mode: "cors"/);
assert.match(store, /credentials: "omit"/);
assert.match(store, /MAX_BYTES = 24 \* 1024 \* 1024/);
assert.match(store, /crypto\.subtle\.digest\("SHA-256"/);
assert.match(store, /indexedDB\.open/);
assert.match(store, /ALLOWED/);
assert.match(store, /importLocalMediaFile/);
assert.match(store, /video.*mp4/);
assert.match(renderer, /source_type === "image"/);
assert.match(renderer, /source_type === "image_sequence"/);
assert.match(renderer, /prepareVisualSequence/);
assert.match(renderer, /source_type === "video_clip"/);
assert.match(renderer, /createImageBitmap/);
assert.match(renderer, /loadedmetadata/);
assert.match(renderer, /drawImage\(video/);
assert.match(renderer, /export function startPreparedVisualPlayback/);
assert.match(renderer, /export function stopPreparedVisualPlayback/);
const drawVideo = renderer.slice(renderer.indexOf("export function drawPreparedVisualNow"), renderer.indexOf("export function clearMediaRendererCache"));
assert.doesNotMatch(drawVideo, /video\.currentTime\s*=/, "drawing a frame must never seek the video element");
assert.match(drawVideo, /video\.readyState < 2/);
const app = readFileSync(new URL("../index.html", import.meta.url), "utf8");
assert.match(app, /let renderActiveVideo=null,renderActiveVideoKey=null/);
assert.match(app, /startPreparedVisualPlayback\(renderActiveVideo,sceneProgress\)/);
assert.doesNotMatch(app, /await window\.JAIMediaRenderer\.awaitPreparedVisualFrame/, "master render loop must not await per-frame video seeks");
console.log("Openverse media import, IndexedDB, non-blocking video clock and renderer contracts: PASS");
